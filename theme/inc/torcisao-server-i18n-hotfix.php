function torcisao_server_i18n_hotfix_translate($text,$map){
    if ($text === '') return $text;
    if (!preg_match('/^(\s*)(.*?)(\s*)$/su',$text,$m)) return $text;
    $core=$m[2];
    if (array_key_exists($core,$map)) return $m[1].$map[$core].$m[3];
    return $text;
}

function torcisao_server_i18n_hotfix_buffer($html){
    if (!$html) return $html;
    $lang=function_exists('torcisao_request_language')?torcisao_request_language():'pt';
    if (!in_array($lang,['en','es'],true)) return $html;
    $maps=torcisao_server_i18n_hotfix_maps();
    $map=$maps[$lang]??[];
    if (!$map) return $html;

    $protected=[];
    $html=preg_replace_callback('#<(script|style|noscript)\b[^>]*>.*?</\1>#is',function($m) use (&$protected){
        $token='__TOR_HOTFIX_'.count($protected).'__';
        $protected[$token]=$m[0];
        return $token;
    },$html);

    $html=preg_replace_callback('/>([^<]+)</u',function($m) use ($map){
        return '>'.torcisao_server_i18n_hotfix_translate($m[1],$map).'<';
    },$html);

    $html=preg_replace_callback('/\s(aria-label|title|placeholder|data-label)=("|\')(.*?)\2/isu',function($m) use ($map){
        return ' '.$m[1].'='.$m[2].torcisao_server_i18n_hotfix_translate($m[3],$map).$m[2];
    },$html);

    if ($protected) $html=strtr($html,$protected);
    return $html;
}

function torcisao_start_server_i18n_hotfix(){
    $lang=function_exists('torcisao_request_language')?torcisao_request_language():'pt';
    if (in_array($lang,['en','es'],true)) ob_start('torcisao_server_i18n_hotfix_buffer');
}
add_action('template_redirect','torcisao_start_server_i18n_hotfix',-997);
